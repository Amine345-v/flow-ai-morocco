def clean_code_content(raw: str) -> str:
    """Strips markdown code blocks to return clean source code or document text."""
    if not raw:
        return ""
    match = re.search(r"```(?:\w+)?\n([\s\S]*?)\n```", raw)
    if match:
        return match.group(1).strip()
    return raw.strip()

